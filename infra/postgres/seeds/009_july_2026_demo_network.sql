CREATE TEMP TABLE july_2026_trip_seed ON COMMIT DROP AS
WITH calendar AS (
  SELECT day_value::date
  FROM generate_series('2026-07-18'::date, '2026-07-30'::date, interval '1 day') AS day_value
),
schedules (
  route_id,
  route_code,
  vehicle_id,
  departure_time,
  duration_minutes,
  price_vnd
) AS (
  VALUES
    ('00000000-0000-4000-8000-000000000501'::uuid, 'HCM-DLI', '00000000-0000-4000-8000-000000000401'::uuid, '07:00'::time, 420, 280000),
    ('00000000-0000-4000-8000-000000000501'::uuid, 'HCM-DLI', '00000000-0000-4000-8000-000000000402'::uuid, '15:30'::time, 390, 350000),
    ('00000000-0000-4000-8000-000000000501'::uuid, 'HCM-DLI', '00000000-0000-4000-8000-000000000403'::uuid, '22:00'::time, 420, 240000),
    ('00000000-0000-4000-8000-000000000502'::uuid, 'DLI-HCM', '00000000-0000-4000-8000-000000000402'::uuid, '09:00'::time, 420, 350000),
    ('00000000-0000-4000-8000-000000000503'::uuid, 'HCM-NTR', '00000000-0000-4000-8000-000000000403'::uuid, '06:30'::time, 540, 320000),
    ('00000000-0000-4000-8000-000000000503'::uuid, 'HCM-NTR', '00000000-0000-4000-8000-000000000401'::uuid, '20:00'::time, 540, 300000),
    ('00000000-0000-4000-8000-000000000504'::uuid, 'NTR-HCM', '00000000-0000-4000-8000-000000000401'::uuid, '08:00'::time, 540, 300000),
    ('00000000-0000-4000-8000-000000000505'::uuid, 'HCM-CTO', '00000000-0000-4000-8000-000000000402'::uuid, '07:30'::time, 210, 180000),
    ('00000000-0000-4000-8000-000000000505'::uuid, 'HCM-CTO', '00000000-0000-4000-8000-000000000403'::uuid, '16:00'::time, 210, 160000),
    ('00000000-0000-4000-8000-000000000506'::uuid, 'CTO-HCM', '00000000-0000-4000-8000-000000000403'::uuid, '09:30'::time, 210, 160000),
    ('00000000-0000-4000-8000-000000000507'::uuid, 'DAD-HAN', '00000000-0000-4000-8000-000000000401'::uuid, '18:30'::time, 840, 420000),
    ('00000000-0000-4000-8000-000000000508'::uuid, 'HAN-DAD', '00000000-0000-4000-8000-000000000402'::uuid, '19:00'::time, 840, 430000),
    ('00000000-0000-4000-8000-000000000509'::uuid, 'DLI-NTR', '00000000-0000-4000-8000-000000000403'::uuid, '08:30'::time, 240, 220000),
    ('00000000-0000-4000-8000-000000000510'::uuid, 'NTR-DLI', '00000000-0000-4000-8000-000000000402'::uuid, '13:00'::time, 240, 230000)
),
source AS (
  SELECT
    calendar.day_value,
    schedules.*,
    md5(
      schedules.route_code || '|' || calendar.day_value::text || '|' || schedules.departure_time::text
    ) AS trip_hash
  FROM calendar
  CROSS JOIN schedules
)
SELECT
  (
    substr(trip_hash, 1, 8) || '-' ||
    substr(trip_hash, 9, 4) || '-4' ||
    substr(trip_hash, 14, 3) || '-8' ||
    substr(trip_hash, 18, 3) || '-' ||
    substr(trip_hash, 21, 12)
  )::uuid AS trip_id,
  route_id,
  route_code,
  vehicle_id,
  ((day_value + departure_time) AT TIME ZONE 'Asia/Ho_Chi_Minh') AS departure_at,
  ((day_value + departure_time) AT TIME ZONE 'Asia/Ho_Chi_Minh') +
    make_interval(mins => duration_minutes) AS arrival_at,
  price_vnd
FROM source;

