  (
    substr(fare_hash, 1, 8) || '-' ||
    substr(fare_hash, 9, 4) || '-4' ||
    substr(fare_hash, 14, 3) || '-8' ||
    substr(fare_hash, 18, 3) || '-' ||
    substr(fare_hash, 21, 12)
  )::uuid,
  trip_id,
  price_vnd
FROM (
  SELECT *, md5('fare|' || trip_id::text) AS fare_hash
